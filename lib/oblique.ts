const BY_EN = new Map(OBLIQUE_CARDS.map((c) => [c.en, c]));

// Look up the bilingual entry for a stored card. Falls back to the
// English text alone when the deck has been edited and a previously
// drawn card is no longer in the canonical list.
export function findObliqueCard(en: string): ObliqueCard {
  return BY_EN.get(en) ?? { en, ko: "" };
}

export function pickObliqueCard(exclude: readonly string[] = []): ObliqueCard {
  const exSet = new Set(exclude);
  const pool = OBLIQUE_CARDS.filter((c) => !exSet.has(c.en));
  const fallback = OBLIQUE_CARDS[Math.floor(Math.random() * OBLIQUE_CARDS.length)];
  if (pool.length === 0) return fallback ?? OBLIQUE_CARDS[0];
  return pool[Math.floor(Math.random() * pool.length)] ?? fallback;
}
